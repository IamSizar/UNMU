  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: Text(widget.isEditing ? 'createPostX.editTitle'.tr : 'createPostX.newTitle'.tr),
        actions: [
          // Step-20 (mig 0020, item 4.15) — composing a fresh post can
          // also save as a draft instead of publishing immediately.
          // Hidden in edit mode (existing posts use the regular Save).
          if (!widget.isEditing)
            IconButton(
              tooltip: 'createPostX.saveDraftTooltip'.tr,
              onPressed: _publishing ? null : _saveAsDraft,
              icon: const Icon(Icons.bookmark_outline_rounded),
            ),
          TextButton(
            onPressed: _publishing ? null : _publish,
            child: _publishing
                ? const SizedBox(
                    width: 18,
                    height: 18,
                    child: CircularProgressIndicator(strokeWidth: 2),
                  )
                : Text(widget.isEditing ? 'createPostX.save'.tr : 'createPostX.publish'.tr),
          ),
          const SizedBox(width: 4),
        ],
      ),
      body: SafeArea(
        child: DismissKeyboardOnTap(
        child: Form(
          key: _formKey,
          child: ListView(
            // iPad: center the composer to a comfortable column instead of
            // full-width fields. Phone: unchanged 16px inset.
            padding: EdgeInsets.fromLTRB(
                context.centeringHPad(contentWidth: 680), 12,
                context.centeringHPad(contentWidth: 680), 24),
            children: [
              // ── Card 1: Format ────────────────────────────────
              // The type picker drives which content fields show
              // below, so it's the first decision in the form.
              _Card(
                title: 'createPostX.cardFormat'.tr,
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    _TypePicker(
                      value: _type,
                      onChange: (t) => setState(() => _type = t),
                    ),
                    const SizedBox(height: 10),
                    Text(
                      _typeDescription(_type),
                      style: Theme.of(context).textTheme.bodySmall?.copyWith(
                            color: Theme.of(context).colorScheme.onSurfaceVariant,
                          ),
                    ),
                  ],
                ),
              ),
              const SizedBox(height: 14),
              // ── Card 2: Content ───────────────────────────────
              // Type-specific fields (title / body / media).
              _Card(
                title: 'createPostX.cardContent'.tr,
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: _fieldsForType(),
                ),
              ),
              const SizedBox(height: 14),
              // ── Card 3: Tickers ───────────────────────────────
              _Card(
                title: 'createPostX.cardTickers'.tr,
                titleSuffix: _tickers.isEmpty ? null : '${_tickers.length}',
                child: _TickerInput(
                  controller: _tickerInput,
                  items: _tickers,
                  onAdd: (v) =>
                      setState(() => _tickers.add(v.toUpperCase())),
                  onRemove: (i) => setState(() => _tickers.removeAt(i)),
                ),
              ),
              const SizedBox(height: 14),
              // ── Card 4: Audience (new posts only) ─────────────
              // Bundles visibility + destinations + stance into a
              // single card since they all answer "who sees this".
              if (!widget.isEditing) ...[
                _Card(
                  title: 'createPostX.cardAudience'.tr,
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      _SubLabel('createPostX.subVisibility'.tr),
                      const SizedBox(height: 8),
                      _VisibilityPicker(
                        value: _visibility,
                        onChange: (v) => setState(() => _visibility = v),
                      ),
                      const SizedBox(height: 18),
                      _SubLabel('createPostX.subPublishTo'.tr),
                      const SizedBox(height: 8),
                      _DestinationPicker(
                        publishToProfile: _publishToProfile,
                        onProfileChange: (v) =>
                            setState(() => _publishToProfile = v),
                        destinations: _destinations,
                        selectedCommunities: _selectedCommunities,
                        onCommunityToggle: (id) {
                          setState(() {
                            if (_selectedCommunities.contains(id)) {
                              _selectedCommunities.remove(id);
                            } else {
                              _selectedCommunities.add(id);
                            }
                          });
                        },
                        loaded: _destinationsLoaded,
                        communitiesEnabled: true,
                      ),
                      // Stance only when ≥ 1 community is selected
                      // and the type is article (community media
                      // posts default to HOLD silently).
                      if (_type == PostType.article &&
                          _selectedCommunities.isNotEmpty) ...[
                        const SizedBox(height: 18),
                        _SubLabel('createPostX.subStance'.tr),
                        const SizedBox(height: 8),
                        _StancePicker(
                          value: _stance,
                          onChange: (s) => setState(() => _stance = s),
                        ),
                      ],
                    ],
                  ),
                ),
              ] else ...[
                // Edit mode just gets the visibility toggle — no
                // destination switching after publish.
                _Card(
                  title: 'createPostX.cardVisibility'.tr,
                  child: _VisibilityPicker(
                    value: _visibility,
                    onChange: (v) => setState(() => _visibility = v),
