        // Flutter 3.x adds a `fontSize == null || fontSize > 0` assertion
        // on `StrutStyle` that crashes the screen whenever this branch
        // builds (Studio → New Post → Reel). Use a `FormField<String>`
        // instead: it participates in Form.validate() the same way but
        // renders nothing unless there's an error to display.
        FormField<String>(
          validator: (_) {
            if (_mediaUrl.text.trim().isEmpty) {
              return _type == PostType.reel
                  ? 'createPostX.pickReelToUpload'.tr
                  : 'createPostX.pickVideoToUpload'.tr;
            }
            return null;
          },
          builder: (state) {
            final err = state.errorText;
            if (err == null) return const SizedBox.shrink();
            return Padding(
              padding: const EdgeInsets.only(top: 6),
              child: Text(
                err,
                style: TextStyle(
                  color: Theme.of(context).colorScheme.error,
                  fontSize: 12.5,
                  height: 1.35,
                ),
              ),
            );
          },
        ),
      ],
    ];
  }
}

/// Reusable picker tile — shows a "Pick…" button when empty, a thumbnail-ish
/// card when a file is picked + uploaded, and a spinner while uploading.
class _MediaPickerTile extends StatelessWidget {
  final IconData icon;
  final String emptyLabel;
  final bool uploading;
  /// 0..1 chunked-upload progress. When provided AND non-zero, the
  /// uploading state renders a real progress bar instead of a generic
  /// spinner. Cover uploads (single-shot) keep passing 0 / null and
  /// fall back to the spinner-only branch.
  final double? uploadProgress;
  final String? uploadedUrl;
  final File? localFile;
  final VoidCallback onPick;
  final VoidCallback onRemove;
  /// Optional override for the small subtitle under the filename when a
  /// file is uploaded. Used to mark the cover as auto-generated.
  final String? subtitleOverride;

  const _MediaPickerTile({
    required this.icon,
    required this.emptyLabel,
    required this.uploading,
    required this.uploadedUrl,
    required this.localFile,
    required this.onPick,
    required this.onRemove,
    this.uploadProgress,
    this.subtitleOverride,
  });

  @override
  Widget build(BuildContext context) {
    final cs = Theme.of(context).colorScheme;
    if (uploading) {
      // Use a determinate bar when chunked-upload progress is wired in
      // (videos). Cover / image uploads still pass null and get the
      // legacy spinner — that path is single-shot and there's no
      // progress to report.
      final hasProgress = uploadProgress != null && uploadProgress! > 0;
      final pct = hasProgress
          ? '${(uploadProgress!.clamp(0.0, 1.0) * 100).toStringAsFixed(0)}%'
          : null;
      return Container(
        padding: const EdgeInsets.all(14),
        decoration: BoxDecoration(
          color: cs.surfaceContainerHighest.withValues(alpha: 0.4),
          borderRadius: BorderRadius.circular(12),
          border: Border.all(color: cs.outlineVariant.withValues(alpha: 0.4)),
        ),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              children: [
                SizedBox(
                  width: 18,
                  height: 18,
                  child: hasProgress
                      ? CircularProgressIndicator(
                          strokeWidth: 2,
                          value: uploadProgress!.clamp(0.0, 1.0),
                        )
                      : const CircularProgressIndicator(strokeWidth: 2),
                ),
                const SizedBox(width: 12),
                Expanded(
                  child: Text(
                    pct == null
                        ? 'createPostX.uploading'.tr
                        : 'createPostX.uploadingPct'.trParams({'pct': pct}),
                    style: Theme.of(context).textTheme.bodyMedium,
                  ),
                ),
              ],
            ),
            if (hasProgress) ...[
              const SizedBox(height: 10),
              ClipRRect(
                borderRadius: BorderRadius.circular(4),
                child: LinearProgressIndicator(
                  minHeight: 4,
                  value: uploadProgress!.clamp(0.0, 1.0),
                  backgroundColor: cs.outlineVariant.withValues(alpha: 0.4),
                ),
              ),
            ],
          ],
        ),
      );
    }
    if (uploadedUrl != null) {
      final filename = localFile?.uri.pathSegments.last ?? 'createPostX.uploaded'.tr;
      return Container(
        padding: const EdgeInsets.all(12),
        decoration: BoxDecoration(
          color: cs.primary.withValues(alpha: 0.08),
          borderRadius: BorderRadius.circular(12),
          border: Border.all(color: cs.primary.withValues(alpha: 0.4)),
        ),
        child: Row(
          children: [
            Icon(Icons.check_circle_rounded, color: cs.primary, size: 20),
            const SizedBox(width: 10),
            Expanded(
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                mainAxisSize: MainAxisSize.min,
                children: [
                  Text(
                    filename,
                    overflow: TextOverflow.ellipsis,
                    style: Theme.of(context).textTheme.bodyMedium?.copyWith(
                          fontWeight: FontWeight.w700,
                        ),
                  ),
                  Text(
                    subtitleOverride ?? 'createPostX.uploaded'.tr,
                    style: Theme.of(context).textTheme.labelSmall?.copyWith(
                          color: cs.onSurfaceVariant,
                        ),
                  ),
                ],
              ),
            ),
            TextButton(
              onPressed: onPick,
              child: Text('createPostX.replace'.tr),
            ),
            IconButton(
              tooltip: 'createPostX.removeTooltip'.tr,
              icon: const Icon(Icons.close_rounded, size: 18),
              onPressed: onRemove,
            ),
          ],
        ),
      );
    }
    return InkWell(
      onTap: onPick,
      borderRadius: BorderRadius.circular(12),
      child: Container(
        padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 18),
        decoration: BoxDecoration(
          borderRadius: BorderRadius.circular(12),
          border: Border.all(
            color: cs.outlineVariant.withValues(alpha: 0.55),
            style: BorderStyle.solid,
          ),
          color: cs.surfaceContainerHighest.withValues(alpha: 0.25),
        ),
        child: Row(
          children: [
            Container(
              width: 36,
              height: 36,
              decoration: BoxDecoration(
                color: cs.primary.withValues(alpha: 0.15),
                borderRadius: BorderRadius.circular(10),
              ),
              alignment: Alignment.center,
              child: Icon(icon, color: cs.primary, size: 20),
            ),
            const SizedBox(width: 12),
            Expanded(
              child: Text(
                emptyLabel,
                style: Theme.of(context).textTheme.bodyMedium?.copyWith(
                      fontWeight: FontWeight.w600,
                    ),
              ),
            ),
            Icon(Icons.add_rounded, color: cs.primary),
          ],
        ),
      ),
    );
  }
}

