/// Composer for a new expert post — pick **type** first (article / video /
/// reel), then fill in the relevant fields, then publish.
///
/// Pops with the freshly-created [ExpertPost] on success so the caller (the
/// studio dashboard) can prepend it without a full refresh.
///
/// In **edit mode** (pass [existingPost]) the form is pre-populated and the
/// save button calls PATCH instead of POST. Pops with the updated post on
/// success.
class CreatePostScreen extends StatefulWidget {
  /// When non-null, the screen runs in edit mode for this existing post.
  final ExpertPost? existingPost;

  const CreatePostScreen({super.key}) : existingPost = null;

  /// Edit an existing post. Title / body / media url / cover url /
  /// duration / visibility / tickers are pre-filled; the type is fixed
  /// (you can't change article ↔ video on an existing row).
  const CreatePostScreen.edit({super.key, required ExpertPost post})
      : existingPost = post;

  bool get isEditing => existingPost != null;

  @override
  State<CreatePostScreen> createState() => _CreatePostScreenState();
}

class _CreatePostScreenState extends State<CreatePostScreen> {
  final _formKey = GlobalKey<FormState>();
  final _title = TextEditingController();
  final _body = TextEditingController();
  final _mediaUrl = TextEditingController();
  final _coverUrl = TextEditingController();
  final _duration = TextEditingController();
  final _tickerInput = TextEditingController();
  final List<String> _tickers = [];

  PostType _type = PostType.article;
  PostVisibility _visibility = PostVisibility.subscribersOnly;
  bool _publishing = false;
  String? _error;

  // ── Destination picker state ────────────────────────────────────
  // The composer can fan-out to:
  //   * the expert's own profile (default ON),
  //   * any community the expert has joined (article-only — the
  //     community endpoint doesn't accept video/reel media).
  //
  // [_destinations] is the joined-community catalog used to render
  // the checkbox list. Loaded once on initState via the backend's
  // /me/communities endpoint, then cross-referenced against the
  // mock Community data for display name + region color (until
  // a real /communities/:id GET is wired through).
  bool _publishToProfile = true;
  final Set<String> _selectedCommunities = <String>{};
  List<mock.Community> _destinations = const [];
  bool _destinationsLoaded = false;
  /// Required by the community endpoint when posting an article.
  /// Stays `HOLD` by default; only surfaced in the UI when at
  /// least one community is selected.
  String _stance = 'HOLD';

  // ── Media-picker state (video / cover) ──
  // Once a file is picked we upload it to the backend and store the resulting
  // URL on _mediaUrl / _coverUrl. While the upload is in flight, we show a
  // spinner instead of the picked-file row so the user can't double-tap.
  File? _pickedVideoLocal;
  File? _pickedCoverLocal;
  bool _uploadingVideo = false;
  /// 0..1 progress of the chunked video upload. Driven by the
  /// onProgress callback from [UploadService.uploadVideoChunked]. Stays
  /// at 0 while resolving init / probing duration; ramps up as chunks
  /// land; reaches 1.0 right before /complete fires.
  double _videoUploadProgress = 0.0;
  bool _uploadingCover = false;
  String? _mediaPickError;

  /// True when the cover was auto-generated by snapping a frame from the
  /// uploaded video. Drives a small "Auto-generated" hint on the cover
  /// picker tile + the "Replace" affordance for overriding it.
  bool _coverIsAuto = false;

  // Global background-upload manager + listeners that mirror its progress
  // and result back into this screen, so the inline tile and the global
  // UploadStatusPill stay in sync — and the upload keeps running if the
  // user leaves this screen mid-upload.
  late final UploadController _uploadCtrl;
  Worker? _progWorker;
  Worker? _phaseWorker;

  @override
  void initState() {
    super.initState();
    _uploadCtrl = Get.find<UploadController>();
    _uploadingVideo = _uploadCtrl.isActive;
    _progWorker = ever<double>(_uploadCtrl.progress, (p) {
      if (mounted) setState(() => _videoUploadProgress = p);
    });
    _phaseWorker = ever<UploadPhase>(_uploadCtrl.phase, (ph) {
      if (!mounted) return;
      setState(() {
        _uploadingVideo = _uploadCtrl.isActive;
        if (ph == UploadPhase.success) {
          final url = _uploadCtrl.resultUrl.value;
          if (url != null && url.isNotEmpty) _mediaUrl.text = url;
        } else if (ph == UploadPhase.failed) {
          _pickedVideoLocal = null;
          _mediaPickError = _uploadCtrl.error.value;
        }
      });
    });
    final existing = widget.existingPost;
    if (existing != null) {
      // Edit mode — pre-fill every field from the existing post.
      _type = existing.postType;
      _visibility = existing.visibility;
      _title.text = existing.title ?? '';
      _body.text = existing.body;
      _mediaUrl.text = existing.mediaUrl ?? '';
      _coverUrl.text = existing.coverUrl ?? '';
      _duration.text =
          existing.durationSeconds != null ? '${existing.durationSeconds}' : '';
      _tickers.addAll(existing.tickers);
    } else {
      // New-post mode only — load joined communities so the
      // destination picker can render. Edit mode keeps the legacy
      // single-target flow (you can't change targetType after
      // publish).
      _loadDestinations();
    }
  }

  /// Pull the list of communities the expert has joined and
  /// cross-reference the mock community catalog for display
  /// metadata. Failure leaves the destination list empty — the
  /// picker degrades to "Profile only" gracefully.
  Future<void> _loadDestinations() async {
    // Community kill-switch — when communities are disabled, don't offer
    // any community destinations; the composer degrades to "Profile only".
    if (!Get.find<AppConfigController>().communityEnabled.value) {
      if (mounted) setState(() => _destinationsLoaded = true);
      return;
    }
    final res = await CommunityService.myCommunityIds();
    if (!mounted) return;
    final ids = res.ids ?? const <String>{};
    final list = <mock.Community>[];
    for (final entry in mock.MockSocialData.communities) {
      if (ids.contains(entry.id)) list.add(entry);
    }
    setState(() {
      _destinations = list;
      _destinationsLoaded = true;
    });
  }

  @override
  void dispose() {
    _progWorker?.dispose();
    _phaseWorker?.dispose();
    _title.dispose();
    _body.dispose();
    _mediaUrl.dispose();
    _coverUrl.dispose();
    _duration.dispose();
    _tickerInput.dispose();
    super.dispose();
  }

  /// Pick a video, validate its duration, then upload it to the backend.
  /// On success, _mediaUrl is filled with the absolute URL the backend
  /// served back. For reels, rejects anything > 60s with a friendly inline
  /// error.
  Future<void> _pickAndUploadVideo() async {
    setState(() => _mediaPickError = null);

    final result = await FilePicker.platform.pickFiles(
      type: FileType.video,
      allowMultiple: false,
      withData: false,
    );
    if (result == null || result.files.single.path == null) return;
    final file = File(result.files.single.path!);

    // Show "Reading video…" in the global pill while we probe duration —
    // the step that used to feel like a silent freeze.
    _uploadCtrl.beginReading('Reading video…');

    // Inspect duration via video_player itself — works for any container
    // VideoPlayerController can later play back, which is exactly the set
    // of files we accept anyway. Time-boxed so a stubborn file can't hang
    // the picker forever — on timeout we just skip the length check.
    int seconds;
    final probe = VideoPlayerController.file(file);
    try {
      await probe.initialize().timeout(const Duration(seconds: 20));
      final dur = probe.value.duration;
      seconds = dur.inSeconds;
    } catch (e) {
      _uploadCtrl.cancelReading();
      setState(() => _mediaPickError =
          'createPostX.couldNotReadVideo'.trParams({'error': '$e'}));
      await probe.dispose();
      return;
    }
    await probe.dispose();

    if (seconds <= 0) {
      _uploadCtrl.cancelReading();
      setState(() => _mediaPickError =
          'createPostX.couldNotDetectDuration'.tr);
      return;
    }
    if (_type == PostType.reel && seconds > 60) {
      _uploadCtrl.cancelReading();
      final m = seconds ~/ 60;
      final s = seconds % 60;
      setState(() => _mediaPickError = 'createPostX.reelTooLong'.trParams(
          {'duration': '$m:${s.toString().padLeft(2, '0')}'}));
      return;
    }

    setState(() {
      _pickedVideoLocal = file;
      _uploadingVideo = true;
      _videoUploadProgress = 0.0;
      _duration.text = '$seconds';
    });

    // Hand the transfer to the global UploadController. It owns the
    // direct-to-S3, resumable upload, so it KEEPS RUNNING if the user
    // leaves this screen — the floating UploadStatusPill shows progress on
    // every screen. The `ever` listeners wired in initState mirror its
    // progress + final URL back into this screen (and surface any error on
    // _mediaPickError). Fire-and-forget so the composer stays interactive.
    _uploadCtrl.startVideoUpload(file);

    // Auto-generate a cover from the video — only when the user hasn't
    // already picked one. Sarah's manual cover always wins.
    if (_coverUrl.text.trim().isEmpty) {
      // Choose a frame near the start: 1s for normal-length clips, the
      // first frame if the clip is shorter than that.
      final atMs = seconds >= 1 ? 1000 : 0;
      await _generateAutoCover(file, atMs);
    }
  }

  /// Snap a frame from [video] at [atMs] milliseconds, upload it, and put
  /// the resulting URL on _coverUrl. Silently bails on failure — a missing
  /// cover just means the card shows a black frame with the play button,
  /// which is still functional.
  Future<void> _generateAutoCover(File video, int atMs) async {
    setState(() => _uploadingCover = true);
    try {
      final tmpDir = await getTemporaryDirectory();
      final outPath = await vt.VideoThumbnail.thumbnailFile(
        video: video.path,
        thumbnailPath: tmpDir.path,
        imageFormat: vt.ImageFormat.JPEG,
        timeMs: atMs,
        quality: 85,
        maxWidth: 720,
      );
      if (outPath == null || outPath.isEmpty) {
        if (mounted) setState(() => _uploadingCover = false);
        return;
      }
      final thumbFile = File(outPath);
      if (!thumbFile.existsSync()) {
        if (mounted) setState(() => _uploadingCover = false);
        return;
      }
      final res = await UploadService.uploadImage(thumbFile);
      if (!mounted) return;
      if (res.error != null || res.url == null) {
        // Cover upload failed — that's fine, post still works without it.
        setState(() => _uploadingCover = false);
        return;
      }
      setState(() {
        _uploadingCover = false;
        _pickedCoverLocal = thumbFile;
        _coverUrl.text = res.url!;
        _coverIsAuto = true;
      });
    } catch (_) {
      // Frame extraction can fail on weird codecs / permissions — just
      // skip it. The user can still pick a cover manually if they want.
      if (mounted) setState(() => _uploadingCover = false);
    }
  }

  /// Pick a cover image manually — overrides any auto-generated cover.
  /// No size/aspect-ratio validation client-side; backend caps at 8 MB.
  Future<void> _pickAndUploadCover() async {
    setState(() => _mediaPickError = null);

    final result = await FilePicker.platform.pickFiles(
      type: FileType.image,
      allowMultiple: false,
      withData: false,
    );
    if (result == null || result.files.single.path == null) return;
    final file = File(result.files.single.path!);

    setState(() {
      _pickedCoverLocal = file;
      _uploadingCover = true;
      // Sarah picking her own cover always replaces the auto one.
      _coverIsAuto = false;
    });
    final res = await UploadService.uploadImage(file);
    if (!mounted) return;
    if (res.error != null) {
      setState(() {
        _uploadingCover = false;
        _pickedCoverLocal = null;
        _mediaPickError = res.error;
      });
      return;
    }
    setState(() {
      _uploadingCover = false;
      _coverUrl.text = res.url ?? '';
    });
  }

  void _clearVideo() {
    setState(() {
      _pickedVideoLocal = null;
      _mediaUrl.clear();
      _duration.clear();
      // Removing the video also wipes any auto-cover we generated for it.
      // Manual covers stay (Sarah might have intentionally set one).
      if (_coverIsAuto) {
        _pickedCoverLocal = null;
        _coverUrl.clear();
        _coverIsAuto = false;
      }
    });
  }

  void _clearCover() {
    setState(() {
      _pickedCoverLocal = null;
      _coverUrl.clear();
      _coverIsAuto = false;
    });
  }

  /// Save-as-draft path (mig 0020, item 4.15). Same field validation
  /// as publish but routes through `/me/expert/drafts` and skips the
  /// destination picker — drafts always live on the expert's own
  /// profile until the user explicitly publishes (and at publish-time
  /// the destination picker reappears in a future patch). For now,
  /// drafts are profile-scoped only.
  Future<void> _saveAsDraft() async {
    HapticUtils.tap();
    setState(() {
      _publishing = true;
      _error = null;
    });
    final res = await ExpertPostService.saveDraft(
      postType: _type,
      title: _title.text.trim().isEmpty ? null : _title.text.trim(),
      body: _body.text.trim().isEmpty ? null : _body.text.trim(),
      mediaUrl: _mediaUrl.text.trim().isEmpty ? null : _mediaUrl.text.trim(),
      coverUrl: _coverUrl.text.trim().isEmpty ? null : _coverUrl.text.trim(),
      durationSeconds: int.tryParse(_duration.text.trim()),
      visibility: _visibility,
      tickers: List.of(_tickers),
    );
    if (!mounted) return;
    setState(() => _publishing = false);
    if (res.error != null) {
      setState(() => _error = res.error);
      return;
    }
    ScaffoldMessenger.of(context).showSnackBar(SnackBar(
      content: Text('createPostX.savedToDrafts'.tr),
      behavior: SnackBarBehavior.floating,
      duration: const Duration(seconds: 2),
    ));
    Navigator.of(context).pop(res.post);
  }

  Future<void> _publish() async {
    if (!_formKey.currentState!.validate()) return;
    HapticUtils.confirm();
    final auth = Get.find<AuthController>();
    // For new posts the expertId comes from the authed user (only experts
    // can publish). For edits, use the existing post's expertId so the URL
    // path resolves correctly even if auth scope is fuzzy.
    final expertId =
        widget.existingPost?.expertId ?? auth.user?.expertId;
    if (expertId == null) {
      setState(() => _error = 'createPostX.onlyExperts'.tr);
      return;
    }

    // ── Edit mode short-circuit ───────────────────────────────
    // Editing keeps the legacy single-target flow (no destination
    // picker). The `target_type` of an existing row can't change
    // after publish — that would mean copying the row across
    // tables.
    if (widget.isEditing) {
      setState(() {
        _publishing = true;
        _error = null;
      });
      final existing = widget.existingPost!;
      final result = await ExpertPostService.update(
        expertId: expertId,
        postId: existing.id,
        title: _title.text.trim(),
        body: _body.text.trim(),
        mediaUrl: _mediaUrl.text.trim(),
        coverUrl: _coverUrl.text.trim(),
        durationSeconds: int.tryParse(_duration.text.trim()),
        visibility: _visibility,
        tickers: _tickers,
      );
      if (!mounted) return;
      if (result.post != null) {
        Navigator.of(context).pop(result.post);
        return;
      }
      setState(() {
        _publishing = false;
        _error = result.error ?? 'createPostX.updateFailed'.tr;
      });
      return;
    }

    // ── New post mode: validate destinations ──────────────────
    // The user must select at least one place to publish. Profile
    // is selected by default; communities require an explicit
    // checkbox tick. Communities now accept all post types
    // (article, video, reel) so we no longer gate the eligible set
    // on type.
    final eligibleCommunities = _selectedCommunities;
    if (!_publishToProfile && eligibleCommunities.isEmpty) {
      setState(() =>
          _error = 'createPostX.pickDestination'.tr);
      return;
    }
    // Community endpoint requires a single ticker symbol; without one
    // the row would fail server-side. Surface the requirement here so
    // the user fixes it before we fire requests.
    if (eligibleCommunities.isNotEmpty && _tickers.isEmpty) {
      setState(() => _error =
          'createPostX.tickerRequired'.tr);
      return;
    }

    setState(() {
      _publishing = true;
      _error = null;
    });

    // Fan-out: capture each destination's result so we can show
    // partial-success / partial-failure feedback.
    ExpertPost? profileResult;
    String? profileError;
    final communityErrors = <String, String>{}; // communityId → error msg
    final communityNames = <String, String>{}; // communityId → display name
    for (final c in _destinations) {
      communityNames[c.id] = c.name;
    }

    if (_publishToProfile) {
      final result = await ExpertPostService.create(
        expertId: expertId,
        type: _type,
        visibility: _visibility,
        title: _title.text.trim(),
        body: _body.text.trim(),
        mediaUrl: _mediaUrl.text.trim().isEmpty ? null : _mediaUrl.text.trim(),
        coverUrl: _coverUrl.text.trim().isEmpty ? null : _coverUrl.text.trim(),
        durationSeconds: int.tryParse(_duration.text.trim()),
        tickers: _tickers,
      );
      profileResult = result.post;
      profileError = result.error;
    }

    // Community posts use the community endpoint. Single ticker is
    // taken from the first entry in [_tickers]; the stance picker
    // defaults to HOLD when not surfaced.
    final firstTicker = _tickers.isEmpty ? '' : _tickers.first;
    // Stance is meaningful for articles only; default HOLD silently
    // for video / reel community posts (the column is non-null on
    // the schema so we always send something).
    final outboundStance = _type == PostType.article ? _stance : 'HOLD';
    for (final cid in eligibleCommunities) {
      final res = await ExpertPostService.createCommunityPost(
        communityId: cid,
        type: _type,
        visibility: _visibility,
        title: _title.text.trim(),
        body: _body.text.trim(),
        ticker: firstTicker,
        stance: outboundStance,
        mediaUrl: _mediaUrl.text.trim().isEmpty ? null : _mediaUrl.text.trim(),
        coverUrl: _coverUrl.text.trim().isEmpty ? null : _coverUrl.text.trim(),
        durationSeconds: int.tryParse(_duration.text.trim()),
        tickers: _tickers,
      );
      if (res.error != null) {
        communityErrors[cid] = res.error!;
      }
    }

    if (!mounted) return;

    // ── Decide what to do based on results ────────────────────
    final anyProfileFail = _publishToProfile && profileError != null;
    final anyCommunityFail = communityErrors.isNotEmpty;
    final anySuccess = (_publishToProfile && profileResult != null) ||
        (eligibleCommunities.length > communityErrors.length);

    if (!anySuccess) {
      // Total failure — keep the screen open with the error.
      setState(() {
        _publishing = false;
        _error = profileError ?? communityErrors.values.first;
      });
      return;
    }

    // At least one destination succeeded. Pop with the profile post
    // (when we have one) so the studio can prepend it. Surface a
    // snackbar if any destination failed so the user knows what
    // didn't make it.
    if (anyProfileFail || anyCommunityFail) {
      final failed = <String>[];
      if (anyProfileFail) failed.add('createPostX.yourProfileFailLabel'.tr);
      for (final entry in communityErrors.entries) {
        failed.add(communityNames[entry.key] ?? entry.key);
      }
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          duration: const Duration(seconds: 4),
          content: Text(
            'createPostX.publishedButFailed'.trParams({'list': failed.join(', ')}),
          ),
        ),
      );
    }
    Navigator.of(context).pop(profileResult);
  }

