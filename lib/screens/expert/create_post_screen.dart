        if (_duration.text.isNotEmpty) ...[
          const SizedBox(height: 6),
          Text(
            _type == PostType.reel
                ? 'createPostX.detectedDurationReel'
                    .trParams({'seconds': _duration.text})
                : 'createPostX.detectedDuration'
                    .trParams({'seconds': _duration.text}),
