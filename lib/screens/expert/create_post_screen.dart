                textCapitalization: TextCapitalization.characters,
              ),
            ),
            const SizedBox(width: 8),
            IconButton.filledTonal(
              onPressed: _commit,
              icon: const Icon(Icons.add),
            ),
          ],
        ),
        if (items.isNotEmpty) ...[
          const SizedBox(height: 8),
          Wrap(
            spacing: 8,
            runSpacing: 8,
            children: [
